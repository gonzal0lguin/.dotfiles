# shellcheck shell=bash
module alacritty on "Alacritty terminal from apt (no cargo)"

# Shared by alacritty + kitty: start every terminal window inside tmux?
_ask_tmux_autostart() {
  [[ -n ${TMUX_AUTOSTART:-} ]] && return
  local cur; cur=$(state_get TMUX_AUTOSTART no)
  if ask "Open new terminal windows directly inside tmux (a new session per window)?" "${cur:0:1}"; then
    TMUX_AUTOSTART=yes
  else
    TMUX_AUTOSTART=no
  fi
  export TMUX_AUTOSTART
}

alacritty_configure() { _ask_tmux_autostart; }

alacritty_install() {
  apt_install alacritty
  if has snap && snap list alacritty >/dev/null 2>&1; then
    if (( ! NO_PACKAGES )) && ask "Alacritty is also installed as a snap (it leaks snap env vars into your shells). Remove the snap?" y; then
      run $SUDO snap remove alacritty
    else
      manual "Alacritty is installed twice (apt + snap). Consider: sudo snap remove alacritty"
    fi
  fi

  link_pkg alacritty
  local dir="$HOME/.config/alacritty" auto=${TMUX_AUTOSTART:-$(state_get TMUX_AUTOSTART no)}
  state_set TMUX_AUTOSTART "$auto"
  seed_file "$dir/local.toml.example" "$dir/local.toml"
  if (( ! DRY_RUN )); then
    if [[ $auto == yes ]]; then
      printf '# generated by install.sh\n[shell]\nprogram = "tmux"\nargs = ["new-session"]\n' >"$dir/autostart.toml"
    else
      printf '# generated by install.sh (tmux autostart: off)\n' >"$dir/autostart.toml"
    fi
  fi
}
