# shellcheck shell=bash
module tmux on "tmux config, status bar (stats/minimal), TPM + resurrect/continuum/yank"

tmux_configure() {
  local cur; cur=${TMUX_STATUS:-$(state_get TMUX_STATUS stats)}
  TMUX_STATUS=$(choose "tmux status bar" "$cur" \
    stats "IP, CPU, RAM, GPU (nvidia) and date" \
    minimal "Only host and date")
  local names; names=$(_tmux_name_themes "${TMUX_RANDOM_NAMES:-$(state_get TMUX_RANDOM_NAMES no)}")
  if (( ASSUME_YES )) || [[ ! -t 0 ]]; then
    TMUX_RANDOM_NAMES=${names:-no}
  else
    local picked
    picked=$(ui_multi "Random character names for new tmux windows? (each session uses one universe; none = off)" \
      harrypotter "Harry Potter" "$([[ " $names " == *" harrypotter "* ]] && echo on || echo off)" \
      starwars "Star Wars" "$([[ " $names " == *" starwars "* ]] && echo on || echo off)" \
      marvel "Marvel" "$([[ " $names " == *" marvel "* ]] && echo on || echo off)") || die "cancelled"
    TMUX_RANDOM_NAMES=$(xargs <<<"$picked")   # newline list -> one line
    TMUX_RANDOM_NAMES=${TMUX_RANDOM_NAMES// /,}
    : "${TMUX_RANDOM_NAMES:=no}"
  fi
  export TMUX_STATUS TMUX_RANDOM_NAMES
}

# Saved value -> space separated universes ("yes" from older installs = harrypotter)
_tmux_name_themes() {
  case $1 in no|"") ;; yes) echo harrypotter ;; *) echo "${1//,/ }" ;; esac
}

tmux_install() {
  apt_install tmux xclip
  local cfg="$HOME/.config/tmux" plugins="${XDG_DATA_HOME:-$HOME/.local/share}/tmux/plugins"

  # tmux reads ~/.tmux.conf before ~/.config/tmux/tmux.conf: move old files away
  local old
  for old in "$HOME/.tmux.conf" "$HOME/.random_window_name.sh" "$HOME/tmux_colors.sh"; do
    if [[ -e $old || -L $old ]] && ! _points_to_repo "$old"; then backup_path "$old"; fi
  done

  link_pkg tmux

  local status=${TMUX_STATUS:-$(state_get TMUX_STATUS stats)}
  [[ -f $cfg/status/$status.conf ]] || status=stats
  run ln -sfn "status/$status.conf" "$cfg/status.conf"
  state_set TMUX_STATUS "$status"

  local names=${TMUX_RANDOM_NAMES:-$(state_get TMUX_RANDOM_NAMES no)}
  state_set TMUX_RANDOM_NAMES "$names"
  if (( ! DRY_RUN )); then
    {
      echo "# generated by install.sh — edit choices with: dot install tmux"
      local themes; themes=$(_tmux_name_themes "$names")
      if [[ -n $themes ]]; then
        echo "set -g @name_themes '$themes'"
        echo "set-hook -g session-created \"run-shell '$cfg/scripts/random_window_name.sh session #{window_id}'\""
        echo "set-hook -g after-new-window \"run-shell '$cfg/scripts/random_window_name.sh window #{window_id}'\""
      fi
    } >"$cfg/extras.conf"
  fi

  local p
  for p in tpm tmux-resurrect tmux-continuum tmux-yank; do
    git_sync "https://github.com/tmux-plugins/$p" "$plugins/$p"
  done
  ok "tmux plugins in $plugins"
  info "inside a running tmux, press prefix + r (C-a r) to reload"
}
