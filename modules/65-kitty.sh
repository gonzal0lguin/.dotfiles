# shellcheck shell=bash
module kitty on "kitty terminal (official build in ~/.local, or apt)"

kitty_configure() {
  _ask_tmux_autostart
  local cur; cur=${KITTY_SOURCE:-$(state_get KITTY_SOURCE official)}
  KITTY_SOURCE=$(choose "Install kitty from" "$cur" \
    official "Official build in ~/.local/kitty.app (latest, no sudo)" \
    apt "Ubuntu package (older, e.g. 0.32 on 24.04)")
  export KITTY_SOURCE
}

kitty_install() {
  local src=${KITTY_SOURCE:-$(state_get KITTY_SOURCE official)}
  state_set KITTY_SOURCE "$src"
  if [[ $src == apt ]]; then
    apt_install kitty
  elif [[ -x $HOME/.local/kitty.app/bin/kitty ]]; then
    ok "kitty $("$HOME/.local/kitty.app/bin/kitty" --version | awk '{print $2}') already installed"
  elif (( DRY_RUN )); then
    info "[dry-run] install kitty to ~/.local/kitty.app"
  else
    curl -fsSL https://sw.kovidgoyal.net/kitty/installer.sh | sh /dev/stdin launch=n >/dev/null
    mkdir -p "$LOCAL_BIN" "$HOME/.local/share/applications"
    ln -sf "$HOME/.local/kitty.app/bin/kitty" "$HOME/.local/kitty.app/bin/kitten" "$LOCAL_BIN/"
    # desktop entries, as documented by kitty
    cp "$HOME"/.local/kitty.app/share/applications/kitty*.desktop "$HOME/.local/share/applications/"
    sed -i "s|Icon=kitty|Icon=$HOME/.local/kitty.app/share/icons/hicolor/256x256/apps/kitty.png|g; s|Exec=kitty|Exec=$HOME/.local/kitty.app/bin/kitty|g" \
      "$HOME"/.local/share/applications/kitty*.desktop
    ok "installed kitty"
  fi

  link_pkg kitty
  local dir="$HOME/.config/kitty" auto=${TMUX_AUTOSTART:-$(state_get TMUX_AUTOSTART no)}
  seed_file "$dir/local.conf.example" "$dir/local.conf"
  if (( ! DRY_RUN )); then
    if [[ $auto == yes ]]; then
      printf '# generated by install.sh\nshell tmux new-session -A -s main\n' >"$dir/autostart.conf"
    else
      printf '# generated by install.sh (tmux autostart: off)\n' >"$dir/autostart.conf"
    fi
  fi
}
